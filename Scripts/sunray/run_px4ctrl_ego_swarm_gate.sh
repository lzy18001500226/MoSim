def state_callback(msg):
    global state_samples, connected_sample_count, consecutive_connected_samples
    global disconnected_sample_count, first_connected_wall, first_connected_sim
    global last_connected_wall, last_connected_sim, stable_start_wall, stable_start_sim, last_state
    state_samples += 1
    now_wall = time.time()
    now_sim = sim_time_or_none()
    if msg.connected:
        connected_sample_count += 1
        consecutive_connected_samples += 1
        if first_connected_wall is None:
            first_connected_wall = now_wall
            first_connected_sim = now_sim
        last_connected_wall = now_wall
        last_connected_sim = now_sim
        if stable_start_wall is None:
            stable_start_wall = now_wall
            stable_start_sim = now_sim
    else:
        disconnected_sample_count += 1
        consecutive_connected_samples = 0
        stable_start_wall = None
        stable_start_sim = None
    last_state = {
        "topic": topic,
        "connected": bool(msg.connected),
        "armed": bool(msg.armed),
        "guided": bool(msg.guided),
        "manual_input": bool(msg.manual_input),
        "mode": msg.mode,
        "system_status": int(msg.system_status),
    }


def services_ready():
    for name in required_services:
        try:
            rospy.wait_for_service(name, timeout=service_probe_timeout_s)
            service_status[name] = True
        except rospy.ROSException:
            service_status[name] = False
    return all(service_status.values())

subscriber = rospy.Subscriber(topic, State, state_callback, queue_size=1)
while time.time() < deadline and not rospy.is_shutdown():
    stable_elapsed = 0.0 if stable_start_wall is None else max(0.0, time.time() - stable_start_wall)
    if (
        last_state is not None
        and last_state["connected"]
        and consecutive_connected_samples >= min_state_samples
        and stable_elapsed >= stable_wall_s
        and services_ready()
    ):
        with open(output, "w", encoding="utf-8") as f:
            json.dump(payload("passed"), f, indent=2, ensure_ascii=False)
            f.write("\n")
        os._exit(0)
    time.sleep(0.05)

with open(output, "w", encoding="utf-8") as f:
    json.dump(payload("timeout", "no_stable_connected_state_and_services_before_timeout"), f, indent=2, ensure_ascii=False)
    f.write("\n")
os._exit(1)
PY
}

request_stream_rate() {
  local uid="$1"
  if [[ "${MAVROS_STREAM_RATE_HZ}" == "0" || "${MAVROS_STREAM_RATE_HZ}" == "0.0" ]]; then
    return 0
  fi
  {
    echo "MAVROS_STREAM_RATE_HZ=${MAVROS_STREAM_RATE_HZ}"
    echo "MAVROS_SET_STREAM_GROUPS=${MAVROS_SET_STREAM_GROUPS}"
    for group in ${MAVROS_SET_STREAM_GROUPS}; do
      case "${group}" in
        raw_sensors) stream_id=1 ;;
        position) stream_id=6 ;;
        extra1) stream_id=10 ;;
        extra2) stream_id=11 ;;
        *) echo "skip_unknown_stream_group ${group}"; continue ;;
      esac
      echo "set_stream_rate ${group}(${stream_id}) ${MAVROS_STREAM_RATE_HZ}Hz"
      timeout 8s rosservice call "/uav${uid}/mavros/set_stream_rate" "stream_id: ${stream_id}
message_rate: ${MAVROS_STREAM_RATE_HZ}
on_off: true" || true
    done
    if [[ "${MAVROS_SET_MESSAGE_INTERVALS}" == "true" ]]; then
      local interval_us
      interval_us="$(python3 - <<PY
rate = float("${MAVROS_STREAM_RATE_HZ}")
print(int(round(1000000.0 / rate)))
PY
)"
      echo "MAVROS_SET_MESSAGE_IDS=${MAVROS_SET_MESSAGE_IDS}"
      for spec in ${MAVROS_SET_MESSAGE_IDS}; do
        local msg_id msg_name
        msg_id="${spec%%:*}"
        msg_name="${spec#*:}"
        echo "set_message_interval ${msg_name}(${msg_id}) ${interval_us}us"
        timeout 8s rosservice call "/uav${uid}/mavros/cmd/command" "broadcast: false
command: 511
confirmation: 0
param1: ${msg_id}
param2: ${interval_us}
param3: 0
param4: 0
param5: 0
param6: 0
param7: 0" || true
      done
    fi
  } > "${RESULT_DIR}/uav${uid}_mavros_stream_rate_request.txt" 2>&1
}

apply_px4_int_param_override() {
  local uid="$1"
  local param_id="$2"
  local value="$3"
  if [[ -z "${value}" ]]; then
    return 0
  fi
  {
    echo "PARAM_OVERRIDE ${param_id}=${value}"
    if [[ "${PX4CTRL_PARAM_PULL_BEFORE_OVERRIDE}" == "true" ]]; then
      echo "PARAM_PULL_BEFORE_OVERRIDE"
      timeout 15s rosservice call "/uav${uid}/mavros/param/pull" "force_pull: true" || true
    fi
    echo "PARAM_SET_SERVICE ${param_id}=${value}"
    timeout 8s rosservice call "/uav${uid}/mavros/param/set" "param_id: '${param_id}'
value:
  integer: ${value}
  real: 0.0" || true
    echo "PARAM_SET_MAVPARAM ${param_id}=${value}"
    timeout 12s rosrun mavros mavparam -n "/uav${uid}/mavros" set "${param_id}" "${value}" || true
    echo "PARAM_VERIFY_SERVICE ${param_id}"
    timeout 5s rosservice call "/uav${uid}/mavros/param/get" "param_id: '${param_id}'" || true
    echo "PARAM_VERIFY_MAVPARAM ${param_id}"
    timeout 8s rosrun mavros mavparam -n "/uav${uid}/mavros" get "${param_id}" || true
  } >> "${RESULT_DIR}/uav${uid}_px4_param_overrides.txt" 2>&1
}

apply_px4_param_override() {
  local uid="$1"
  local param_id="$2"
  local value="$3"
  if [[ -z "${param_id}" || -z "${value}" ]]; then
    return 0
  fi
  local integer_value="0"
  local real_value="0.0"
  if [[ "${value}" =~ ^-?[0-9]+$ ]]; then
    integer_value="${value}"
  else
    real_value="${value}"
  fi
  {
    echo "PARAM_OVERRIDE ${param_id}=${value}"
    if [[ "${PX4CTRL_PARAM_PULL_BEFORE_OVERRIDE}" == "true" ]]; then
      echo "PARAM_PULL_BEFORE_OVERRIDE"
      timeout 15s rosservice call "/uav${uid}/mavros/param/pull" "force_pull: true" || true
    fi
    echo "PARAM_SET_SERVICE ${param_id}=${value}"
    timeout 8s rosservice call "/uav${uid}/mavros/param/set" "param_id: '${param_id}'
value:
  integer: ${integer_value}
  real: ${real_value}" || true
    echo "PARAM_SET_MAVPARAM ${param_id}=${value}"
    timeout 12s rosrun mavros mavparam -n "/uav${uid}/mavros" set "${param_id}" "${value}" || true
    echo "PARAM_VERIFY_SERVICE ${param_id}"
    timeout 5s rosservice call "/uav${uid}/mavros/param/get" "param_id: '${param_id}'" || true
    echo "PARAM_VERIFY_MAVPARAM ${param_id}"
    timeout 8s rosrun mavros mavparam -n "/uav${uid}/mavros" get "${param_id}" || true
  } >> "${RESULT_DIR}/uav${uid}_px4_param_overrides.txt" 2>&1
}

