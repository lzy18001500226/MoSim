wait_topic_sample() {
  local topic="$1"
  local output="$2"
  local timeout_s="$3"
  python3 - "${topic}" "${output}" "${timeout_s}" <<'PY'
import json
import os
import sys
import time

import rospy
from rospy.msg import AnyMsg

topic = sys.argv[1]
output = sys.argv[2]
timeout_s = float(sys.argv[3])
deadline = time.time() + timeout_s
attempts = 0
rospy.init_node(f"mosim_wait_topic_sample_{os.getpid()}", anonymous=True, disable_signals=True)
while time.time() < deadline and not rospy.is_shutdown():
    attempts += 1
    try:
        msg = rospy.wait_for_message(topic, AnyMsg, timeout=min(4.0, max(0.1, deadline - time.time())))
    except rospy.ROSException:
        continue
    payload = {
        "topic": topic,
        "attempts": attempts,
        "received": True,
        "wall_time": time.time(),
        "raw_bytes": len(msg._buff),
    }
    with open(output, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2, ensure_ascii=False)
        f.write("\n")
    os._exit(0)

payload = {
    "topic": topic,
    "attempts": attempts,
    "received": False,
    "wall_time": time.time(),
    "error": "no_sample_before_timeout",
}
with open(output, "w", encoding="utf-8") as f:
    json.dump(payload, f, indent=2, ensure_ascii=False)
    f.write("\n")
os._exit(1)
PY
}

