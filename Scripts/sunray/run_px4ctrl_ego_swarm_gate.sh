    echo "PX4CTRL_START_EXTERNAL_FUSION=${PX4CTRL_START_EXTERNAL_FUSION}"
    echo "PX4CTRL_EXTERNAL_FUSION_USE_VISION_POSE=${PX4CTRL_EXTERNAL_FUSION_USE_VISION_POSE}"
