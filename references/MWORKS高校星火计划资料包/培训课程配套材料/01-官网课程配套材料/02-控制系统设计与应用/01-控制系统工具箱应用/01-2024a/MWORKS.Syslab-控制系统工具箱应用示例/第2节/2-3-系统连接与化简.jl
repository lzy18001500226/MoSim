##【示例17】模型简化处理
## 1.将上述模型先进行一个均衡状态空间实现
G = tf([1, 11, 36, 26], [1, 14.6, 74.96, 153.7, 99.65])
# 均衡状态空间模型实现
Gb, g = balreal(ss(G))

## 2.通过modred()函数从均衡实现中消除对系统影响较小的状态
# 消除影响较小的两个状态
Gdel = modred(Gb, [3, 4], method=:Truncate)

## 原始系统与降阶系统的频率特性对比
w = logspace(-2, 2, 50)
bode(Gdel, w, "--or", markersize=5, linewidth=1.5)
bode(Gdel, w, "-b", linewidth=0.75, ishold=true)
bodegrid(true)
legend(["Gdel-降阶系统", "G-原系统"])
