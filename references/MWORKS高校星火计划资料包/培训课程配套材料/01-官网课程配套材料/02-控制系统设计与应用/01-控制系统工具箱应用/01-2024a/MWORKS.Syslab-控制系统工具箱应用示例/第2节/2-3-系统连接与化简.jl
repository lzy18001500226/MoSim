##【示例16】5阶双输入双输出系统的最小实现
# 系统矩阵定义
A = [-6 -1.5 2 4 9.5; -6 -2.5 2 5 12.5; -5 0.25 -0.5 3.5 9.75; -1 0.5 0 -1 1.5; -2 -1 1 2 3]
B = [6 4; 5 5; 3 4; 0 2; 3 1]
C = [2 0.75 -0.5 -1.5 -2.75; 0 -1.25 1.5 1.5 2.25]
D = zeros(2, 2)
# 系统创建
G = ss(A, B, C, D)
# 通过minreal函数求取系统最小实现
Gr = minreal(G)
#原系统与最小实现系统的阶跃响应对比
step(Gr, 0:0.3:20, "--ro", markersize=4, linewidth=0.5)
step(G, 20, "-b", ishold=true, linewidth=1)
grid("on")

